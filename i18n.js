function i18nPack(locale) {
  return I18N[locale] || I18N.en;
}

function t(locale, key, vars = {}) {
  let text = i18nPack(locale).ui[key] || I18N.en.ui[key] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}

function mealLabel(id, locale) {
  return i18nPack(locale).meals[id] || id;
}

function localeTag(locale) {
  if (locale === "hi") return "hi-IN";
  if (locale === "mr") return "mr-IN";
  return "en-IN";
}
